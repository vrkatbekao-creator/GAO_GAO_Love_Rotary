export function getLocalizedEvent(ev, lang = 'zh') {
  if (lang === 'zh' || !EVENT_TRANSLATIONS[ev.id]?.[lang]) {
    return ev;
  }
  const tr = EVENT_TRANSLATIONS[ev.id][lang];
  return {
    ...ev,
    title: tr.title || ev.title,
    choices: ev.choices.map(c => ({
      ...c,
      label: tr[c.id] || c.label
    }))
  };
}
